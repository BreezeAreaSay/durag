export type Key = keyof typeof dict.ru;

let current: Lang = 'ru';

export function setLang(lang: string | undefined): void {
  current = lang && lang.toLowerCase().startsWith('ru') ? 'ru' : lang ? 'en' : 'ru';
}

export function getLang(): Lang {
  return current;
}

export function t(key: Key, vars?: Record<string, string | number>): string {
  const table: Record<string, string> = dict[current];
  let s = table[key] ?? dict.en[key] ?? key;
  if (vars) {
    for (const [k, v] of Object.entries(vars)) s = s.replace(`{${k}}`, String(v));
  }
  return s;
}

/**
 * Picks the noun form for a count: `one|few|many` (Russian rules, e.g. 1 карта / 2 карты / 5 карт,
 * 21 карта / 12 карт); English uses `one|other`.
 */
export function countWord(n: number | string, key: Key): string {
  const forms = t(key).split('|');
  const one = forms[0] ?? '';
  const few = forms[1] ?? one;
  const many = forms[2] ?? few;
  const v = Math.abs(Math.trunc(Number(n))) || 0;
  if (current === 'ru') {
    const m10 = v % 10;
    const m100 = v % 100;
    if (m10 === 1 && m100 !== 11) return one;
    if (m10 >= 2 && m10 <= 4 && (m100 < 12 || m100 > 14)) return few;
    return many;
  }
  return v === 1 ? one : many;
}

/** Translates a server error code, falling back to the server message. */
export function errorText(code: string | undefined, fallback: string): string {
  if (!code) return fallback;
  const key = `err.${code}` as Key;
  const table: Record<string, string> = dict[current];
  return table[key] ?? fallback;
}
